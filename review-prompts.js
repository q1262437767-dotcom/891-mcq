  function card(prompt, answer, points) {
    return { prompt: prompt, answer: answer, points: points };
  }

  function generic(q, turn) {
    var correct = q.options[q.answer];
    var reason = q.explain.replace(/^解析[：:]\s*/, '');
    var stem = q.q.replace(/[（(]\s*[)）]/g, '____');
    var asksForCandidate = /下列|以下|哪[一种项个些类组]|下述|正确的是|错误的是|不包括|不属于|说法.*是|判断.*是/.test(stem);
    var asksForException = /不包括|不属于|错误的是|不正确的是|下列不是|不能归入|不符合/.test(stem);
    var requiresSet = asksForCandidate && /最|大小顺序|排序|组合|依次排序/.test(stem);
    var expected = asksForException ? '原题要求选出例外或错误项，对应内容为“' + correct + '”。' : '题干的参考答复为“' + correct + '”。';
    var mode = turn % 3;
    if (mode === 0 && !asksForCandidate && !asksForException) {
      return card(stem + '\n不看选项，直接填答，并写出判断依据；若是计算题，请保留列式和单位。',
        correct + '\n' + reason, '先核对结论，再核对理由。计算时单独检查单位和数量级。');
    }

    // For negative and comparative stems, preserve the whole reference set when it
    // determines what the stem means. A student must justify a verdict, not click a letter.
    var context = requiresSet ? stem : stem.replace(/下列|下述|以下(?=说法|因素|选项|情况|过程|成分|条件)/g, '');
    if (requiresSet) {
      context += '\n原题所比较的材料：' + q.options.map(function (option, i) {
        return '（' + (i + 1) + '）' + option;
      }).join('；');
    }
    var others = q.options.filter(function (_, i) { return i !== q.answer; });
    var round = Math.floor(turn / 3);
    var trial = (Number(q.id) + turn) % 3 === 0 ? correct : others[(Number(q.id) + round + mode) % others.length];
    if (mode === 2) {
      var sample = (Number(q.id) + round) % 2 ? others[(Number(q.id) + round + 1) % others.length] : correct;
      return card(context + '\n有人对“' + sample + '”这个作答拿不准。请写一段批注，说明它能否回答题干，并独立给出完整答复。',
        (sample === correct ? '这份作答符合题意。' : '这份作答不符合题意。') + expected + '\n' + reason,
        '对照题干的条件与正反问法；给出能支持最终结论的依据。');
    }
    return card(context + '\n同学的作答是“' + trial + '”。判断这份作答是否符合题意；写出理由，必要时改正。',
      (trial === correct ? '符合题意。' : '不符合题意。') + expected + '\n' + reason,
      '能判断同学的作答，并说明一道主观题可采用的理由或列式。');
  }

  window.ReviewPrompts = {
    get: function (q, stage) {
      var turn = Math.max(0, Math.floor(Number(stage)) || 0);
      var rows = variants[q.id];
      if (!rows) return generic(q, turn);
      var row = rows[turn % rows.length];
      return card(row[0], row[1], row[2]);
    }
  };
